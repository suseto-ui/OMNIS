// Automatically generate .env from environment variables if .env.example exists,
// ensuring secrets are transferred from the platform's Secret Manager to BuildConfig.
val exampleFile = rootProject.file(".env.example")
val envFile = rootProject.file(".env")
if (exampleFile.exists()) {
    val lines = exampleFile.readLines()
    val envLines = lines.map { line ->
        if (line.trim().startsWith("#") || line.trim().isEmpty() || !line.contains("=")) {
            line
        } else {
            val parts = line.split("=", limit = 2)
            val key = parts[0].trim()
            val envValue = System.getenv(key)
            if (envValue != null && envValue.isNotEmpty()) {
                "$key=$envValue"
            } else {
                line
            }
        }
    }
    envFile.writeText(envLines.joinToString("\n"))
}

